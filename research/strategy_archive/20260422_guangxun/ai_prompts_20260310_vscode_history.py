# ==================== 选股分析提示词 ====================
PROMPT_STOCK_ANALYSIS = """\
以下是今日超短线候选股票数据，请逐一分析并输出评分结果。

## 候选股票
{stock_list}

## 字段说明
- change: 今日涨幅(%)
- volume_ratio: 量比（当日成交量/前5日均量，>1.5表示资金活跃）
- main_net_inflow: 主力资金净流入（万元，正值为净流入）
- is_limit_up: 是否涨停
- trend: 走势标签

## 输出要求
输出一个JSON数组，每个元素对应一只股票，格式如下：
[
  {{
    "code": "股票代码（原样复制，纯数字）",
    "name": "股票名称（原样复制）",
    "sector_score": 板块强度评分（0-100的整数，不要加引号）,
    "sentiment": "正面或中性或负面（三选一）",
    "risk": "无或中等或高（三选一）",
    "reason": "三句话理由，不超过40字"
  }}
]

## 评分标准
sector_score（板块强度，0-100整数）：
- 90-100：板块近期强势轮动，涨停家数多，资金持续流入
- 70-89：板块有一定热度，有龙头带动
- 50-69：板块一般，跟随大盘
- 0-49：板块弱势或无明显热点

sentiment（短线资金情绪）：
- 正面：量比>1.5 且 主力净流入>0 且 涨幅>3%
- 负面：主力净流出 或 量比<1 或 涨幅异常
- 中性：其余情况

risk（风险等级）：
- 高：换手率>8% 或 涨幅>10% 或 连续多日涨停后高位
- 中等：换手率5-8% 或 涨幅7-10%
- 无：换手率3-5% 且 涨幅3-7% 且 均线多头排列
"""

